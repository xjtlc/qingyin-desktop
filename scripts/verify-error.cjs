const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { _electron } = require('./test-deps.cjs').loadTestDependency('playwright');
const root = path.join(__dirname, '..');
const dataDir = path.join(root, 'test-output', 'error-data');
fs.mkdirSync(dataDir, { recursive: true });
const invalidFile = path.join(dataDir, '无法解码的测试文件.mp3');
fs.writeFileSync(invalidFile, '<html>This is a deliberate unsupported audio fixture.</html>');
fs.writeFileSync(path.join(dataDir, 'library.json'), JSON.stringify([{ path: invalidFile }]));
fs.writeFileSync(path.join(dataDir, 'preferences.json'), JSON.stringify({ preferences: { volume: 0 } }));
let application;
(async () => {
  const env = { ...process.env, QINGYIN_TEST: '1', QINGYIN_TEST_DATA: dataDir }; delete env.ELECTRON_RUN_AS_NODE;
  application = await _electron.launch({ executablePath: process.argv[2] || require('electron'), args: process.argv[2] ? [] : [root], cwd: root, env });
  const page = await application.firstWindow();
  await page.locator('.discover-hero').waitFor(); await page.locator('[data-view="local"]').click();
  await page.locator('.track-title[data-action="play-song"]').click();
  await page.locator('.toast.error').waitFor();
  await page.waitForTimeout(500);
  assert.equal(await page.locator('.toast.error').count(), 1);
  const message = await page.locator('.toast.error').innerText();
  assert.doesNotMatch(message, /Failed to|supported source|NotSupportedError/);
  assert.ok(/[\u4e00-\u9fff]/.test(message));
  assert.equal(await page.locator('#audio').evaluate(audio => audio.paused), true);
  assert.match(await page.locator('#play-button').getAttribute('title'), /重试/);
  console.log(JSON.stringify({ unsupportedMediaSingleChineseError: 'PASS', message }));
  await application.close();
})().catch(async error => { console.error(error.name + ': ' + error.message); await application?.close().catch(() => {}); process.exit(1); });
