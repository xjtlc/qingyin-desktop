const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { _electron } = require('./test-deps.cjs').loadTestDependency('playwright');
const root = path.join(__dirname, '..');
const output = path.join(root, 'test-output');
const data = path.join(output, 'ui-data');
fs.mkdirSync(data, { recursive: true });
const first = path.join(data, '验证音乐 一.wav'), second = path.join(data, '验证音乐 二.wav');
fs.copyFileSync(path.join(output, 'native-data', '音频播放验证.wav'), first);
fs.copyFileSync(first, second);
fs.writeFileSync(path.join(data, 'library.json'), JSON.stringify([{ path: first }, { path: second }]));
fs.writeFileSync(path.join(data, 'preferences.json'), JSON.stringify({ preferences: { volume: 0 }, favorites: [], history: [] }));
let application;
(async () => {
  const env = { ...process.env, QINGYIN_TEST: '1', QINGYIN_TEST_DATA: data };
  delete env.ELECTRON_RUN_AS_NODE;
  application = await _electron.launch({ executablePath: process.argv[2] || require('electron'), args: process.argv[2] ? [] : [root], cwd: root, env, timeout: 30000 });
  const page = await application.firstWindow();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.locator('.discover-hero').waitFor();
  await page.locator('.playlist-card').first().waitFor({ timeout: 25000 });
  const recommendationCount = await page.locator('.playlist-card').count();
  await page.screenshot({ path: path.join(output, 'home.png') });
  await page.locator('[data-view="local"]').click();
  await page.waitForFunction(() => document.querySelectorAll('.track-row').length === 2);
  await page.locator('.track-title[data-action="play-song"]').first().click();
  await page.waitForFunction(() => !document.querySelector('#audio').paused && document.querySelector('#audio').currentTime > 0.3);
  assert.match(await page.locator('#player-title').innerText(), /验证音乐 一/);
  await page.locator('#player-favorite').click();
  await page.waitForFunction(async () => (await window.music.store.get()).favorites?.length === 1);
  await page.locator('#seek').evaluate(element => { element.value = '50'; element.dispatchEvent(new Event('input', { bubbles: true })); element.dispatchEvent(new Event('change', { bubbles: true })); });
  assert.ok(await page.locator('#audio').evaluate(audio => audio.currentTime >= 4));
  await page.locator('#next-button').click();
  await page.waitForFunction(() => document.querySelector('#player-title').textContent.includes('验证音乐 二') && !document.querySelector('#audio').paused);
  await page.locator('#play-button').click();
  assert.equal(await page.locator('#audio').evaluate(audio => audio.paused), true);
  await page.locator('#queue-button').click();
  assert.equal(await page.locator('.queue-row').count(), 2);
  await page.locator('#queue-panel [data-action="queue"]').click();
  await page.locator('#lyrics-button').click();
  await page.locator('#lyrics-panel').waitFor({ state: 'visible' });
  await page.keyboard.press('Escape');
  await page.locator('[data-view="favorites"]').click();
  assert.equal(await page.locator('.track-row').count(), 1);
  await page.screenshot({ path: path.join(output, 'local-player.png') });
  await page.keyboard.press('Control+k');
  await page.locator('#search-input').fill('送别');
  await page.locator('#search-input').press('Enter');
  await page.locator('.error-card [data-action="account"]').waitFor({ timeout: 25000 });
  await page.locator('.error-card [data-action="account"]').click();
  await page.locator('#qr-frame img').waitFor({ timeout: 40000 });
  const qrImage = await page.locator('#qr-frame img').getAttribute('src');
  assert.match(qrImage, /^data:image\/png;base64,/);
  assert.ok((await page.locator('#login-modal').innerText()).includes('酷狗概念版 App'));
  await page.screenshot({ path: path.join(output, 'login-test.png') });
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#modal-layer').isHidden(), true);
  const status = await page.evaluate(() => window.music.invoke('status'));
  assert.equal(status.data.loggedIn, false);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ nativeUI: 'PASS', recommendationCount, localPlayback: 'PASS', seekNextPause: 'PASS', favoritesQueueLyrics: 'PASS', searchLoginCTA: 'PASS', realConceptQr: 'PASS', errors }));
  fs.writeFileSync(path.join(output, 'ui-results.json'), JSON.stringify({ nativeUI: 'PASS', recommendationCount, privateAccountPlayback: 'awaiting user QR authorization', errors }, null, 2));
  await application.close();
})().catch(async error => { console.error(error.stack); await application?.close().catch(() => {}); process.exit(1); });
